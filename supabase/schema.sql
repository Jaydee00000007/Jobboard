-- Jobboard production schema
-- Public listings are readable by visitors. User-owned records are private.
create table if not exists public.jobs (
  id bigint generated by default as identity primary key,
  initials text not null default '',
  title text not null,
  company text not null,
  location text not null,
  employment_type text not null check (employment_type in ('Full-time','Part-time','Contract','Internship','Freelance')),
  experience_level text not null check (experience_level in ('Entry level','Mid level','Senior','Lead / Manager')),
  work_mode text not null check (work_mode in ('Remote','Hybrid','On-site','Remote-friendly')),
  category text not null,
  salary_text text not null default '',
  salary_rank text not null default 'medium' check (salary_rank in ('low','medium','high')),
  description text not null default '',
  application_url text,
  source_url text,
  posted_at timestamptz not null default now(),
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists jobs_active_posted_idx on public.jobs (is_active, posted_at desc);
create index if not exists jobs_category_idx on public.jobs (category);
create index if not exists jobs_location_idx on public.jobs (location);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text not null default '',
  role text not null default '',
  location text not null default '',
  phone_number text not null default '',
  skills text[] not null default '{}',
  about text not null default '',
  birth_date date,
  linkedin_url text not null default '',
  resume_name text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.saved_jobs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  job_id bigint not null references public.jobs(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (user_id, job_id)
);
create index if not exists saved_jobs_user_idx on public.saved_jobs(user_id);
create index if not exists saved_jobs_job_id_idx on public.saved_jobs(job_id);
create table if not exists public.applications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  job_id bigint not null references public.jobs(id) on delete cascade,
  status text not null default 'Applied' check (status in ('Applied','Interview','Under review','Offer','Not selected')),
  applied_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, job_id)
);
create index if not exists applications_user_idx on public.applications(user_id);
create index if not exists applications_job_id_idx on public.applications(job_id);
create index if not exists jobs_created_by_idx on public.jobs(created_by);

alter table public.jobs enable row level security;
alter table public.profiles enable row level security;
alter table public.saved_jobs enable row level security;
alter table public.applications enable row level security;
drop policy if exists "Active jobs are publicly viewable" on public.jobs;
create policy "Active jobs are publicly viewable" on public.jobs for select to anon, authenticated using (is_active = true);
drop policy if exists "Users read their own profile" on public.profiles;
create policy "Users read their own profile" on public.profiles for select to authenticated using ((select auth.uid()) = id);
drop policy if exists "Users insert their own profile" on public.profiles;
create policy "Users insert their own profile" on public.profiles for insert to authenticated with check ((select auth.uid()) = id);
drop policy if exists "Users update their own profile" on public.profiles;
create policy "Users update their own profile" on public.profiles for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);
drop policy if exists "Users manage their own saved jobs" on public.saved_jobs;
create policy "Users manage their own saved jobs" on public.saved_jobs for all to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Users manage their own applications" on public.applications;
create policy "Users manage their own applications" on public.applications for all to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

grant select on public.jobs to anon, authenticated;
grant select, insert, update on public.profiles to authenticated;
grant select, insert, update, delete on public.saved_jobs to authenticated;
grant select, insert, update, delete on public.applications to authenticated;

create or replace function public.handle_new_jobboard_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, email)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'name', ''), coalesce(new.email, ''))
  on conflict (id) do nothing;
  return new;
end;
$$;
revoke execute on function public.handle_new_jobboard_user() from public, anon, authenticated;
drop trigger if exists on_jobboard_user_created on auth.users;
create trigger on_jobboard_user_created after insert on auth.users
for each row execute procedure public.handle_new_jobboard_user();
